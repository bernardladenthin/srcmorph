package net.ladenthin.srcmorph.config;

import java.util.List;
import lombok.ToString;
import org.jspecify.annotations.Nullable;

/**
 * A named, reusable group of {@link FactCounter}s, registered in the {@code factDefinitions} list of
 * the configuration file and referenced from a routing rule by
 * {@link RoutingRule#getFactsKey() factsKey}.
 *
 * <p>Mirrors {@code promptDefinitions}: define a fact set once (e.g. {@code java-facts},
 * {@code sql-facts}) and reference it from every rule that needs it, instead of repeating the same
 * {@code facts} list inline on each rule.</p>
 *
 * <p><strong>Note:</strong> this class must remain a mutable JavaBean with setters because the
 * configuration file is bound through them. {@code toString} is generated by Lombok;
 * {@code equals}/{@code hashCode} are intentionally NOT generated (instances are configuration data
 * managed by key in a lookup, and the mutable JavaBean shape makes value semantics unsafe).</p>
 *
 * @see net.ladenthin.srcmorph.facts.FactGroups
 * @see FactCounter
 */
@ToString
public class FactDefinition {

    /** Creates a new {@link FactDefinition}. */
    public FactDefinition() {
        // no-op
    }

    /** Lookup key referenced by {@link RoutingRule#getFactsKey()}. */
    private @Nullable String key;

    /** The fact counters this group contributes. */
    private @Nullable List<FactCounter> facts;

    /** The file the counters are read from instead of {@link #facts}, see {@link net.ladenthin.srcmorph.facts.FactDefinitionLoader}. */
    private @Nullable String factsFile;

    /**
     * Returns the lookup key.
     *
     * @return the key, or {@code null} if not set
     */
    public @Nullable String getKey() {
        return key;
    }

    /**
     * Sets the lookup key.
     *
     * @param key the key
     */
    public void setKey(final @Nullable String key) {
        this.key = key;
    }

    /**
     * Returns the fact counters, or {@code null} when none are configured.
     *
     * @return the fact counters, or {@code null}
     */
    public @Nullable List<FactCounter> getFacts() {
        return facts;
    }

    /**
     * Sets the fact counters.
     *
     * @param facts the fact counters
     */
    public void setFacts(final @Nullable List<FactCounter> facts) {
        this.facts = facts;
    }

    /**
     * Returns the file the counters are read from.
     *
     * @return path of the facts file ({@code label<TAB>pattern} per line), or {@code null} when the
     *         counters are given inline
     */
    public @Nullable String getFactsFile() {
        return factsFile;
    }

    /**
     * Sets the file the counters are read from, instead of inline {@link #setFacts facts}.
     *
     * @param factsFile path of the facts file, relative to the configuration's {@code profileDirectory}
     *                  (or the working directory without one), or absolute
     */
    public void setFactsFile(final @Nullable String factsFile) {
        this.factsFile = factsFile;
    }
}
