package net.ladenthin.srcmorph.config;

import lombok.ToString;
import org.jspecify.annotations.Nullable;

/**
 * One deterministic "fact" counter for an oversize routing rule: a human-readable {@link #label} paired
 * with a {@link #pattern} (a Java regular expression). The number of non-overlapping matches of
 * {@code pattern} across the <em>whole</em> source is reported next to {@code label} in the generated
 * body, giving exact counts the AI cannot reliably produce (it never sees the whole file when the source
 * is chunked/sampled).
 *
 * <p>Language-agnostic by design: the meaning is entirely in the regex the operator writes, so the same
 * mechanism counts {@code (?m)^\s*INSERT\b} rows in a SQL dump, {@code \bboolean\b} occurrences in Java,
 * or {@code (?m)^\s*def\b} functions in Python. Multi-line matching is opt-in via the inline flag
 * {@code (?m)} in the pattern; no flags are applied implicitly.</p>
 *
 * <p>A counter with {@link #ignore} set is not reported: its matches are blanked out of the source
 * (every character except the line breaks) before the other counters count, so a region such as
 * Perl POD, a shell heredoc or an XML comment does not count as code while the line structure, and with
 * it every {@code ^} anchor, stays as it was.</p>
 *
 * <p>A {@link #raw} counter counts the source as written, before any ignore counter blanked it, so a
 * marker that lives in comments (a {@code TODO}) is counted next to counters that skip comments. A
 * {@link #distinct} counter counts the different texts it matched instead of the matches: the first
 * group of the pattern where it took part in the match, the whole match otherwise, so twelve
 * {@code @Inject Clock} are one name.</p>
 *
 * <p><strong>Note:</strong> this class must remain a mutable JavaBean with setters because the
 * configuration file is bound through them (a rule's {@code facts} list, a fact definition's
 * {@code facts}).</p>
 *
 * <p>{@code toString} is generated by Lombok for build-log diagnostics; {@code equals}/{@code hashCode}
 * are intentionally NOT generated (instances are configuration data managed by position in a list, and
 * the mutable JavaBean shape makes value semantics unsafe).</p>
 *
 * @see net.ladenthin.srcmorph.facts.AiFactExtractor
 */
@ToString
public class AiFactCounter {

    /** Creates a new {@link AiFactCounter}. */
    public AiFactCounter() {
        // no-op
    }

    /** Human-readable label shown next to the count (e.g. {@code "INSERT statements"}). */
    private @Nullable String label;

    /** Java regular expression whose non-overlapping match count over the whole source is reported. */
    private @Nullable String pattern;

    /** Whether the matches are blanked out before counting instead of being counted and reported. */
    private boolean ignore;

    /** Whether the counter counts the source as written, before the ignore counters blank it. */
    private boolean raw;

    /** Whether the counter counts the different texts it matched (its first group) instead of the matches. */
    private boolean distinct;

    /**
     * Returns the human-readable label.
     *
     * @return the label, or {@code null} if not set
     */
    public @Nullable String getLabel() {
        return label;
    }

    /**
     * Sets the human-readable label.
     *
     * @param label the label
     */
    public void setLabel(final @Nullable String label) {
        this.label = label;
    }

    /**
     * Returns the counting regular expression.
     *
     * @return the pattern, or {@code null} if not set
     */
    public @Nullable String getPattern() {
        return pattern;
    }

    /**
     * Sets the counting regular expression.
     *
     * @param pattern the pattern
     */
    public void setPattern(final @Nullable String pattern) {
        this.pattern = pattern;
    }

    /**
     * Returns whether this counter marks regions to leave out instead of counting.
     *
     * @return {@code true} for an ignore counter
     */
    public boolean isIgnore() {
        return ignore;
    }

    /**
     * Sets whether this counter marks regions to leave out instead of counting.
     *
     * @param ignore {@code true} for an ignore counter
     */
    public void setIgnore(final boolean ignore) {
        this.ignore = ignore;
    }

    /**
     * Returns whether this counter counts the source before the ignore counters blank it.
     *
     * @return {@code true} for a raw counter
     */
    public boolean isRaw() {
        return raw;
    }

    /**
     * Sets whether this counter counts the source before the ignore counters blank it.
     *
     * @param raw {@code true} for a raw counter
     */
    public void setRaw(final boolean raw) {
        this.raw = raw;
    }

    /**
     * Returns whether this counter counts the different texts it matched instead of the matches.
     *
     * @return {@code true} for a distinct counter
     */
    public boolean isDistinct() {
        return distinct;
    }

    /**
     * Sets whether this counter counts the different texts it matched instead of the matches.
     *
     * @param distinct {@code true} for a distinct counter
     */
    public void setDistinct(final boolean distinct) {
        this.distinct = distinct;
    }
}
