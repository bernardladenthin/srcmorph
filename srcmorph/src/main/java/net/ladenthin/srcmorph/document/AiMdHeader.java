package net.ladenthin.srcmorph.document;

import java.util.ArrayList;
import java.util.Collection;
import java.util.Collections;
import java.util.List;
import java.util.Objects;
import lombok.EqualsAndHashCode;
import lombok.ToString;
import net.ladenthin.srcmorph.support.ConvertToRecord;

/**
 * Canonical header model for a single {@code .ai.md} document.
 *
 * <p>The header contains only deterministic metadata fields. All AI-generated content
 * is stored in the document body (after the {@code ---} separator), keeping the header
 * machine-parseable without AI involvement.</p>
 *
 * <p>Field semantics:</p>
 * <ul>
 *   <li><b>title</b>: Display title of the node, usually the file name or logical package path.</li>
 *   <li><b>headerVersion</b> ({@code H}): Header format version. Used to detect incompatible header schema changes.</li>
 *   <li><b>checksum</b> ({@code C}): Checksum of the represented node state.
 *     <ul>
 *       <li>For {@code file}: CRC32 of the source file content.</li>
 *       <li>For {@code package}: deterministic CRC32 derived from the direct child entries,
 *           ordered ascending by child name/path.</li>
 *     </ul>
 *   </li>
 *   <li><b>sourceDate</b> ({@code D}): Source date of the represented node state.
 *     <ul>
 *       <li>For {@code file}: last modification timestamp of the source file.</li>
 *       <li>For {@code package}: newest source date of the direct child entries.</li>
 *     </ul>
 *   </li>
 *   <li><b>generatedAt</b> ({@code T}): Timestamp when this {@code .ai.md} document was last generated.</li>
 *   <li><b>generatorVersion</b> ({@code G}): Version of the template/generator implementation that produced this document.</li>
 *   <li><b>aiVersion</b> ({@code A}): Version of the AI summarization logic or AI output schema applied to this document.</li>
 *   <li><b>nodeType</b> ({@code X}): Node type, for example {@code file}, {@code package}, or {@code project}.</li>
 *   <li><b>children</b>: Deterministic child links (markdown), carried in the header so navigation
 *       stays machine-parseable and the AI body stays free-form. For a {@code package}: one link per
 *       child {@code .ai.md} (files and sub-packages). For a {@code project}: one link per package.
 *       Empty for a leaf {@code file}.</li>
 *   <li><b>promptHash</b> ({@code P}), <b>factsHash</b> ({@code N}), <b>modelHash</b> ({@code M}),
 *       <b>childrenHash</b> ({@code K}): the CRC32 of the prompts, the fact counters, the model and the
 *       child summaries the summary was written with ({@code ""} when not recorded).</li>
 * </ul>
 *
 * <p>Important invariants:</p>
 * <ul>
 *   <li>A rewrite is decided by the header version, the node type, the title and the AI version,
 *       always, and by the checksum and the four hashes as the configuration's {@code regenerateOn}
 *       switches say ({@link AiMdRewritePolicy}); the source date, the generation time and the
 *       generator version are recorded only.</li>
 *   <li>Package aggregation must be deterministic. Child traversal order must therefore be stable,
 *       typically ascending by child file name or relative path.</li>
 *   <li>The generator should preserve the body when the structural state did not change.</li>
 * </ul>
 *
 * <p>Record-shaped value type marked {@link net.ladenthin.srcmorph.support.ConvertToRecord} for the future Java&nbsp;17+
 * migration. Accessors are record-style ({@code title()}, {@code headerVersion()}, ...); the letters are
 * the keys of the file only ({@link AiMdHeaderCodec}). {@code equals},
 * {@code hashCode} and {@code toString} are generated by Lombok across all fields (including
 * {@code children}); full value semantics apply.</p>
 */
@ConvertToRecord
@ToString
@EqualsAndHashCode
public final class AiMdHeader {
    private final String title;
    private final String headerVersion;
    private final String checksum;
    private final String sourceDate;
    private final String generatedAt;
    private final String generatorVersion;
    private final String aiVersion;
    private final String nodeType;
    private final List<String> children;
    private final String promptHash;
    private final String factsHash;
    private final String modelHash;
    private final String childrenHash;

    /**
     * Creates a new {@link AiMdHeader} with an explicit child-link list.
     *
     * @param title            display title (typically the file name or package path)
     * @param headerVersion    header format version ({@code H})
     * @param checksum         source-state checksum ({@code C})
     * @param sourceDate       source-state timestamp ({@code D})
     * @param generatedAt      generation timestamp of this {@code .ai.md} ({@code T})
     * @param generatorVersion generator/template version ({@code G})
     * @param aiVersion        AI summarisation logic / output schema version ({@code A})
     * @param nodeType         node type ({@code X}), for example {@code file}, {@code package}, or
     *                         {@code project}
     * @param children         deterministic child links (markdown), e.g. {@code [Foo.java](Foo.java.ai.md)};
     *                         empty for leaf {@code file} nodes. Defensively copied; the stored list is
     *                         unmodifiable.
     */
    public AiMdHeader(
            String title,
            String headerVersion,
            String checksum,
            String sourceDate,
            String generatedAt,
            String generatorVersion,
            String aiVersion,
            String nodeType,
            Collection<String> children) {
        Objects.requireNonNull(title, "title");
        Objects.requireNonNull(headerVersion, "headerVersion");
        Objects.requireNonNull(checksum, "checksum");
        Objects.requireNonNull(sourceDate, "sourceDate");
        Objects.requireNonNull(generatedAt, "generatedAt");
        Objects.requireNonNull(generatorVersion, "generatorVersion");
        Objects.requireNonNull(aiVersion, "aiVersion");
        Objects.requireNonNull(nodeType, "nodeType");
        this.title = title;
        this.headerVersion = headerVersion;
        this.checksum = checksum;
        this.sourceDate = sourceDate;
        this.generatedAt = generatedAt;
        this.generatorVersion = generatorVersion;
        this.aiVersion = aiVersion;
        this.nodeType = nodeType;
        // No separate requireNonNull(children): new ArrayList<>(children) already throws NPE on a
        // null list, so an explicit check would be a redundant, equivalent (un-killable) mutant.
        this.children = Collections.unmodifiableList(new ArrayList<>(children));
        this.promptHash = "";
        this.factsHash = "";
        this.modelHash = "";
        this.childrenHash = "";
    }

    /**
     * Creates a copy of {@code header} with the hashes it is written with.
     *
     * @param header       the header
     * @param promptHash   the CRC32 of the prompts ({@code P}), or {@code ""}
     * @param factsHash    the CRC32 of the fact counters ({@code N}), or {@code ""}
     * @param modelHash    the CRC32 of the model ({@code M}), or {@code ""}
     * @param childrenHash the CRC32 of the child summaries ({@code K}), or {@code ""}
     */
    private AiMdHeader(
            final AiMdHeader header,
            final String promptHash,
            final String factsHash,
            final String modelHash,
            final String childrenHash) {
        Objects.requireNonNull(promptHash, "promptHash");
        Objects.requireNonNull(factsHash, "factsHash");
        Objects.requireNonNull(modelHash, "modelHash");
        Objects.requireNonNull(childrenHash, "childrenHash");
        this.title = header.title;
        this.headerVersion = header.headerVersion;
        this.checksum = header.checksum;
        this.sourceDate = header.sourceDate;
        this.generatedAt = header.generatedAt;
        this.generatorVersion = header.generatorVersion;
        this.aiVersion = header.aiVersion;
        this.nodeType = header.nodeType;
        this.children = header.children;
        this.promptHash = promptHash;
        this.factsHash = factsHash;
        this.modelHash = modelHash;
        this.childrenHash = childrenHash;
    }

    /**
     * Returns this header with the hashes a summary is written with, so a later run can tell what wrote
     * it.
     *
     * @param prompt   the CRC32 of the prompts, or {@code ""}
     * @param facts    the CRC32 of the fact counters, or {@code ""}
     * @param model    the CRC32 of the model, or {@code ""}
     * @param children the CRC32 of the child summaries a package or the project reads, or {@code ""}
     * @return the header with the four hashes
     */
    public AiMdHeader withHashes(final String prompt, final String facts, final String model, final String children) {
        return new AiMdHeader(this, prompt, facts, model, children);
    }

    /**
     * Creates a new {@link AiMdHeader} with no child links (the common case for {@code file} nodes).
     *
     * @param title            display title (typically the file name or package path)
     * @param headerVersion    header format version ({@code H})
     * @param checksum         source-state checksum ({@code C})
     * @param sourceDate       source-state timestamp ({@code D})
     * @param generatedAt      generation timestamp of this {@code .ai.md} ({@code T})
     * @param generatorVersion generator/template version ({@code G})
     * @param aiVersion        AI summarisation logic / output schema version ({@code A})
     * @param nodeType         node type ({@code X}), for example {@code file}, {@code package}, or
     *                         {@code project}
     */
    public AiMdHeader(
            String title,
            String headerVersion,
            String checksum,
            String sourceDate,
            String generatedAt,
            String generatorVersion,
            String aiVersion,
            String nodeType) {
        this(
                title,
                headerVersion,
                checksum,
                sourceDate,
                generatedAt,
                generatorVersion,
                aiVersion,
                nodeType,
                Collections.emptyList());
    }

    /**
     * Returns the display title.
     *
     * @return display title
     */
    public String title() {
        return title;
    }

    /**
     * Returns the header format version.
     *
     * @return header format version
     */
    public String headerVersion() {
        return headerVersion;
    }

    /**
     * Returns the source-state checksum.
     *
     * @return source-state checksum
     */
    public String checksum() {
        return checksum;
    }

    /**
     * Returns the source-state timestamp.
     *
     * @return source-state timestamp
     */
    public String sourceDate() {
        return sourceDate;
    }

    /**
     * Returns the generation timestamp of this {@code .ai.md}.
     *
     * @return generation timestamp
     */
    public String generatedAt() {
        return generatedAt;
    }

    /**
     * Returns the generator/template version.
     *
     * @return generator/template version
     */
    public String generatorVersion() {
        return generatorVersion;
    }

    /**
     * Returns the AI summarisation logic version.
     *
     * @return AI summarisation logic version
     */
    public String aiVersion() {
        return aiVersion;
    }

    /**
     * Returns the node type ({@code file}, {@code package}, or {@code project}).
     *
     * @return node type
     */
    public String nodeType() {
        return nodeType;
    }

    /**
     * Returns the deterministic child links carried in the header — markdown links to each child
     * {@code .ai.md} (files and sub-packages) for a {@code package} node, or to each package for a
     * {@code project} node. Empty for leaf {@code file} nodes. The returned list is unmodifiable.
     *
     * @return unmodifiable list of child-link markdown strings; never {@code null}, possibly empty
     */
    public List<String> children() {
        return children;
    }

    /**
     * Returns the CRC32 of the prompts the summary was written with ({@code ""} when not recorded: a
     * project without an overview, or a summary written before the field existed).
     *
     * @return the prompt hash, or {@code ""}
     */
    public String promptHash() {
        return promptHash;
    }

    /**
     * Returns the CRC32 of the fact counters the summary was written with ({@code ""} without counters,
     * or when not recorded).
     *
     * @return the facts hash, or {@code ""}
     */
    public String factsHash() {
        return factsHash;
    }

    /**
     * Returns the CRC32 of the model the summary was written with ({@code ""} when not recorded).
     *
     * @return the model hash, or {@code ""}
     */
    public String modelHash() {
        return modelHash;
    }

    /**
     * Returns the CRC32 of the child summaries a package or the project was written from ({@code ""} for
     * a file, or when not recorded).
     *
     * @return the children hash, or {@code ""}
     */
    public String childrenHash() {
        return childrenHash;
    }
}
