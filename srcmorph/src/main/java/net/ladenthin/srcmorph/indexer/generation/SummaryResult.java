package net.ladenthin.srcmorph.indexer.generation;

import java.util.Objects;
import lombok.EqualsAndHashCode;
import lombok.ToString;
import net.ladenthin.srcmorph.document.AiMdDocument;
import net.ladenthin.srcmorph.support.ConvertToRecord;
import org.jspecify.annotations.Nullable;

/**
 * Immutable result produced by {@link net.ladenthin.srcmorph.indexer.generation.SummaryGenerator#generate}.
 *
 * <p>Carries the document body text produced by a single processing pass, and whether it is complete.
 * An incomplete result (the model's answer was empty, cut off or missing, see
 * {@link net.ladenthin.srcmorph.provider.IncompleteAnswerException}) carries why, and the indexers
 * never write it.</p>
 *
 * <p>Record-shaped value type marked {@link net.ladenthin.srcmorph.support.ConvertToRecord} for the future Java&nbsp;17+
 * migration. The accessor methods follow record-style ({@code body()}, not
 * {@code getBody()}) so the migration is mechanical. {@code equals}, {@code hashCode}
 * and {@code toString} are generated by Lombok over both fields; full value semantics apply.</p>
 */
@ConvertToRecord
@ToString
@EqualsAndHashCode
public final class SummaryResult {
    private final String body;

    private final @Nullable String incompleteReason;

    /**
     * Creates a complete result.
     *
     * <p>Empty body is allowed (and is the documented default when no body field was generated);
     * {@code null} is not, so callers cannot leak a null body into downstream rendering.</p>
     *
     * @param body body text destined for {@link AiMdDocument#body()}; must not be {@code null} (pass
     *             {@code ""} for no-body)
     * @throws NullPointerException if {@code body} is {@code null}
     */
    public SummaryResult(final String body) {
        this(body, null);
    }

    private SummaryResult(final String body, final @Nullable String incompleteReason) {
        this.body = Objects.requireNonNull(body, "body");
        this.incompleteReason = incompleteReason;
    }

    /**
     * Creates an incomplete result, which is not written.
     *
     * @param reason why the answer is no summary, for the log
     * @return the result, with an empty body
     * @throws NullPointerException if {@code reason} is {@code null}
     */
    public static SummaryResult incomplete(final String reason) {
        return new SummaryResult("", Objects.requireNonNull(reason, "reason"));
    }

    /**
     * Returns the body text.
     *
     * @return body text, never {@code null}; empty for an incomplete result or when no body field was
     *         generated
     */
    public String body() {
        return body;
    }

    /**
     * Returns whether the result is a summary that may be written.
     *
     * @return {@code true} unless the model's answer was incomplete
     */
    public boolean complete() {
        return incompleteReason == null;
    }

    /**
     * Returns why the result is incomplete.
     *
     * @return the reason, or {@code null} for a complete result
     */
    public @Nullable String incompleteReason() {
        return incompleteReason;
    }
}
