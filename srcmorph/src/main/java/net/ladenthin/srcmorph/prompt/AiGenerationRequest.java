package net.ladenthin.srcmorph.prompt;

import java.nio.file.Path;
import java.util.Objects;
import lombok.EqualsAndHashCode;
import lombok.ToString;
import net.ladenthin.srcmorph.support.ConvertToRecord;

/**
 * Immutable request object passed to an {@link net.ladenthin.srcmorph.provider.AiGenerationProvider}: identifies the
 * prompt template, the source file being processed and its current text.
 *
 * <p>Record-shaped value type marked {@link net.ladenthin.srcmorph.support.ConvertToRecord} for the future Java&nbsp;17+
 * migration. Accessors are record-style. {@code equals}, {@code hashCode} and
 * {@code toString} are generated by Lombok over all three fields; full value semantics
 * apply.</p>
 */
@ConvertToRecord
@ToString
@EqualsAndHashCode
public final class AiGenerationRequest {
    private final String promptKey;
    private final Path sourceFile;
    private final String sourceText;

    /**
     * Creates a new {@link AiGenerationRequest}.
     *
     * @param promptKey  key of the prompt template to use
     * @param sourceFile path to the source file being processed
     * @param sourceText contents of the source file
     */
    public AiGenerationRequest(String promptKey, Path sourceFile, String sourceText) {
        Objects.requireNonNull(promptKey, "promptKey");
        Objects.requireNonNull(sourceFile, "sourceFile");
        Objects.requireNonNull(sourceText, "sourceText");
        this.promptKey = promptKey;
        this.sourceFile = sourceFile;
        this.sourceText = sourceText;
    }

    /**
     * Returns the prompt template key.
     *
     * @return prompt template key
     */
    public String promptKey() {
        return promptKey;
    }

    /**
     * Returns the path to the source file.
     *
     * @return source file path
     */
    public Path sourceFile() {
        return sourceFile;
    }

    /**
     * Returns the source file contents.
     *
     * @return source file contents
     */
    public String sourceText() {
        return sourceText;
    }
}
