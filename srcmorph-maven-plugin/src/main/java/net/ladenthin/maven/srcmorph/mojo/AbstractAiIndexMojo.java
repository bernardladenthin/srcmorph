package net.ladenthin.maven.srcmorph.mojo;

import java.io.File;
import java.io.IOException;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.Set;
import lombok.ToString;
import net.ladenthin.srcmorph.config.SrcMorphConfiguration;
import net.ladenthin.srcmorph.config.SrcMorphConfigurationFile;
import net.ladenthin.srcmorph.config.SrcMorphConfigurationFileLoader;
import net.ladenthin.srcmorph.engine.SrcMorphException;
import org.apache.maven.model.Resource;
import org.apache.maven.plugin.AbstractMojo;
import org.apache.maven.plugin.MojoExecutionException;
import org.apache.maven.plugins.annotations.Parameter;
import org.jspecify.annotations.Nullable;

/**
 * Base class of the goals ({@code generate}, {@code aggregate-packages}, {@code aggregate-project},
 * {@code calibrate}, {@code check}). Every goal is configured by one srcmorph configuration file, the
 * CLI's ({@link #configurationFile}, JSON or YAML); the POM names the file and the switches, nothing
 * else. {@link #buildConfiguration(RuleSection)} reads it and fills what it leaves unset from the Maven
 * project: {@code baseDirectory} ({@code ${project.basedir}}), {@code subtrees} (the source directory
 * and the resource directories that exist), {@code projectName} and {@code pluginVersion}. A
 * {@code ${name}} in the file is a Maven property (user, then project, then system), so
 * {@code -Dai.gpuLayers=12} reaches it.
 *
 * <p>{@code toString} is generated by Lombok over the {@code @Parameter} fields so Maven debug logs
 * ({@code -X}) print the goal's resolved parameters. {@code equals}/{@code hashCode} are intentionally
 * NOT generated: Maven instantiates mojos per execution and manages them by identity.</p>
 */
// @Parameter fields are populated by the Maven plugin framework via reflection after
// construction. NullAway is configured via ExcludedFieldAnnotations to skip them; Checker
// Framework has no equivalent option for plugin-framework fields, so we suppress class-level.
@SuppressWarnings("initialization.fields.uninitialized")
@ToString(callSuper = true)
public abstract class AbstractAiIndexMojo extends AbstractMojo {

    /** Creates a new {@link AbstractAiIndexMojo}. */
    protected AbstractAiIndexMojo() {
        // no-op
    }

    /**
     * The srcmorph configuration file, in the CLI's format (JSON or YAML): models, rules, prompts,
     * facts, paths. Relative paths in it resolve against its directory.
     */
    @Parameter(property = "srcmorph.configurationFile", defaultValue = "${project.basedir}/srcmorph.yaml")
    protected File configurationFile;

    /**
     * Global skip switch: when {@code true}, <em>every</em> goal skips and returns immediately. To
     * toggle a single phase instead, use that goal's own {@code skip<Phase>} flag (see
     * {@link #isPhaseSkipped()}).
     */
    @Parameter(property = "srcmorph.skip", defaultValue = "false")
    protected boolean skip;

    /**
     * When {@code true}, regenerates every summary although it is up to date, whatever the file's
     * {@code force} says.
     */
    @Parameter(property = "srcmorph.force", defaultValue = "false")
    protected boolean force;

    /** The project's base directory: the base directory when the file sets none. */
    @Parameter(defaultValue = "${project.basedir}", readonly = true, required = true)
    protected File projectDirectory;

    /** The project's source directory, one of the subtrees when the file sets none. */
    @Parameter(defaultValue = "${project.build.sourceDirectory}", readonly = true)
    protected @Nullable File sourceDirectory;

    /** The project's resources, whose directories are subtrees when the file sets none. */
    @Parameter(defaultValue = "${project.build.resources}", readonly = true)
    protected @Nullable List<Resource> resources;

    /** The project's name: the project index title when the file sets none. */
    @Parameter(defaultValue = "${project.name}", readonly = true)
    protected @Nullable String projectName;

    /** The project's version, recorded in every header when the file sets no {@code pluginVersion}. */
    @Parameter(defaultValue = "${project.version}", readonly = true)
    protected String projectVersion;

    /** The project's build directory, for {@code ${project.build.directory}} in the file. */
    @Parameter(defaultValue = "${project.build.directory}", readonly = true)
    protected @Nullable File buildDirectory;

    /** The project's group id, for {@code ${project.groupId}} in the file. */
    @Parameter(defaultValue = "${project.groupId}", readonly = true)
    protected @Nullable String groupId;

    /** The project's artifact id, for {@code ${project.artifactId}} in the file. */
    @Parameter(defaultValue = "${project.artifactId}", readonly = true)
    protected @Nullable String artifactId;

    /** The project's properties, for a {@code ${name}} in the file. */
    @Parameter(defaultValue = "${project.properties}", readonly = true)
    protected @Nullable Properties projectProperties;

    /** The properties of the Maven command line ({@code -Dname=value}), for a {@code ${name}} in the file. */
    @Parameter(defaultValue = "${session.userProperties}", readonly = true)
    protected @Nullable Properties userProperties;

    /**
     * Returns whether this individual goal (phase) is disabled by its own phase-specific skip flag,
     * independent of the global {@link #skip}.
     *
     * @return {@code true} if this phase's own skip flag is set
     */
    protected abstract boolean isPhaseSkipped();

    /**
     * Returns whether this goal should skip execution: either the global {@link #skip} or this phase's
     * own {@link #isPhaseSkipped()} flag. Skip flags stay mojo-side (a Maven lifecycle concern); an
     * engine always executes when asked.
     *
     * @return {@code true} if the goal must not run
     */
    protected boolean shouldSkip() {
        return skip || isPhaseSkipped();
    }

    /**
     * Reads the configuration file and returns the run configuration of one section's rules, its gaps
     * filled from the Maven project (see the class description) and {@link #force} applied.
     *
     * @param section the rules to run with
     * @return the configuration for the engine
     * @throws MojoExecutionException if the file is missing, cannot be read, or does not bind
     */
    protected SrcMorphConfiguration buildConfiguration(final RuleSection section) throws MojoExecutionException {
        if (!configurationFile.isFile()) {
            throw new MojoExecutionException("No srcmorph configuration file at " + configurationFile
                    + "; create it (the CLI's format, see the plugin README) or point <configurationFile>"
                    + " (-Dsrcmorph.configurationFile) at one");
        }
        final SrcMorphConfigurationFile file;
        try {
            file = SrcMorphConfigurationFileLoader.load(configurationFile.toPath(), projectDirectory, properties());
        } catch (final IOException | IllegalArgumentException e) {
            throw new MojoExecutionException(
                    "Cannot read the srcmorph configuration file " + configurationFile + ": " + e.getMessage(), e);
        }
        final SrcMorphConfiguration config = file.getSrcMorph();
        config.setFieldGenerations(section.rulesOf(file));
        if (config.getSubtrees() == null) {
            config.setSubtrees(projectSubtrees(config.getBaseDirectory()));
        }
        if (config.getProjectName() == null) {
            config.setProjectName(projectName);
        }
        if (config.getPluginVersion().isEmpty()) {
            config.setPluginVersion(projectVersion);
        }
        if (force) {
            config.setForce(true);
        }
        return config;
    }

    /**
     * The properties a {@code ${name}} in the file is replaced by: the system properties, overridden by
     * the project's values a POM names the same way ({@code basedir}, {@code project.basedir},
     * {@code project.build.directory}, {@code project.build.sourceDirectory}, {@code project.groupId},
     * {@code project.artifactId}, {@code project.version}, {@code project.name}), overridden by the
     * project's properties, overridden by the command line's.
     *
     * @return the properties by name
     */
    Map<String, String> properties() {
        final Map<String, String> properties = new HashMap<>();
        putAll(properties, System.getProperties());
        final String basedir = projectDirectory.getAbsolutePath();
        put(properties, "basedir", basedir);
        put(properties, "project.basedir", basedir);
        put(properties, "project.build.directory", buildDirectory == null ? null : buildDirectory.getAbsolutePath());
        put(
                properties,
                "project.build.sourceDirectory",
                sourceDirectory == null ? null : sourceDirectory.getAbsolutePath());
        put(properties, "project.groupId", groupId);
        put(properties, "project.artifactId", artifactId);
        put(properties, "project.version", projectVersion);
        put(properties, "project.name", projectName);
        putAll(properties, projectProperties);
        putAll(properties, userProperties);
        return properties;
    }

    private static void put(final Map<String, String> target, final String name, final @Nullable String value) {
        if (value != null) {
            target.put(name, value);
        }
    }

    private static void putAll(final Map<String, String> target, final @Nullable Properties source) {
        if (source == null) {
            return;
        }
        for (final String name : source.stringPropertyNames()) {
            final String value = source.getProperty(name);
            if (value != null) {
                target.put(name, value);
            }
        }
    }

    /**
     * The subtrees of a file that names none: the project's source directory and resource
     * directories that exist below the base directory, each once. A resource directory that holds the
     * source directory (a POM that packs files of the project directory itself, say) is no source tree
     * and is left out: it would index the whole project, build output included.
     *
     * @param baseDirectory the base directory of the run
     * @return the directories, absolute
     */
    List<String> projectSubtrees(final File baseDirectory) {
        final Set<String> directories = new LinkedHashSet<>();
        addIfBelow(directories, baseDirectory, sourceDirectory);
        final List<Resource> projectResources = resources == null ? Collections.<Resource>emptyList() : resources;
        for (final Resource resource : projectResources) {
            final String directory = resource.getDirectory();
            final File resourceDirectory = directory == null ? null : new File(directory);
            if (resourceDirectory != null && holdsTheSourceDirectory(resourceDirectory)) {
                getLog().info("Resource directory " + resourceDirectory + " is or holds the source directory "
                        + sourceDirectory + "; it is no subtree of its own");
                continue;
            }
            addIfBelow(directories, baseDirectory, resourceDirectory);
        }
        return new ArrayList<>(directories);
    }

    private boolean holdsTheSourceDirectory(final File resourceDirectory) {
        if (sourceDirectory == null) {
            return false;
        }
        final Path resource = resourceDirectory.toPath().toAbsolutePath().normalize();
        return sourceDirectory.toPath().toAbsolutePath().normalize().startsWith(resource);
    }

    private static void addIfBelow(
            final Set<String> directories, final File baseDirectory, final @Nullable File directory) {
        if (directory != null
                && directory.isDirectory()
                && directory
                        .toPath()
                        .toAbsolutePath()
                        .normalize()
                        .startsWith(baseDirectory.toPath().toAbsolutePath().normalize())) {
            directories.add(directory.getAbsolutePath());
        }
    }

    /**
     * Returns {@code cause}'s message for wrapping into a {@link MojoExecutionException}, falling back to
     * {@link Throwable#toString()} when the message is {@code null}.
     *
     * @param cause the caught engine exception
     * @return a non-null message suitable for {@code MojoExecutionException}'s constructor
     */
    protected static String messageOf(final SrcMorphException cause) {
        final String message = cause.getMessage();
        return message != null ? message : cause.toString();
    }

    /**
     * Returns the message of an I/O failure of a run, with where the run reads and writes.
     *
     * @param what   what failed, e.g. {@code "generate the AI index files"}
     * @param config the run's configuration
     * @param cause  the failure
     * @return the message
     */
    protected static String ioMessage(final String what, final SrcMorphConfiguration config, final IOException cause) {
        return "Failed to " + what + " under " + config.getOutputDirectory() + " from base " + config.getBaseDirectory()
                + ": " + cause.getMessage();
    }
}
