"""Writes corpus/sql/library/05_seed_data.sql: deterministic seed data for the library schema.

One single-row INSERT per line, so the row counts are exact and greppable:
15 authors, 110 books, 50 members, 150 loans (325 INSERT statements). The data comes from a
fixed linear congruential generator, so every run writes the same file byte for byte.

Usage: python3 generate-seed-sql.py <output_file>
"""
import sys

AUTHORS, BOOKS, MEMBERS, LOANS = 15, 110, 50, 150

FIRST = ["Ada", "Alan", "Barbara", "Claude", "Dennis", "Edsger", "Frances", "Grace", "Hedy",
         "Ivan", "John", "Ken", "Leslie", "Margaret", "Niklaus", "Radia", "Shafi", "Tim"]
LAST = ["Lovelace", "Turing", "Liskov", "Shannon", "Ritchie", "Dijkstra", "Allen", "Hopper",
        "Lamarr", "Sutherland", "Backus", "Thompson", "Lamport", "Hamilton", "Wirth", "Perlman",
        "Goldwasser", "Berners-Lee"]
WORDS = ["Silent", "Hidden", "Northern", "Broken", "Golden", "Last", "Distant", "Paper", "Glass",
         "River", "Garden", "Engine", "Harbor", "Winter", "Signal", "Archive", "Compass", "Lantern"]
COUNTRIES = ["DE", "GB", "US", "FR", "NL", "CH", "AT", "SE", "IT", "ES"]


class Lcg:
    """Numerical Recipes LCG: fixed across Python versions, unlike the random module's seeding."""

    def __init__(self, seed):
        self.state = seed

    def next(self, bound):
        self.state = (self.state * 1664525 + 1013904223) % 2**32
        return self.state % bound


def main(out_path):
    rnd = Lcg(20261028)
    # The header the generated SQL file carries, not this script's own.
    # REUSE-IgnoreStart
    lines = [
        "-- SPDX-FileCopyrightText: 2026 Bernard Ladenthin <bernard.ladenthin@gmail.com>",
        "--",
        "-- SPDX-License-Identifier: Apache-2.0",
        # REUSE-IgnoreEnd
        "--",
        "-- Lending library: seed data (PostgreSQL). Generated by",
        "-- docs/ai-index-benchmark/tools/generate-seed-sql.py; do not edit by hand.",
        "",
        "BEGIN;",
        "",
    ]
    for i in range(1, AUTHORS + 1):
        name = f"{FIRST[rnd.next(len(FIRST))]} {LAST[rnd.next(len(LAST))]}"
        lines.append(
            "INSERT INTO author (author_id, full_name, birth_year, country_code) VALUES "
            f"({i}, '{name}', {1900 + rnd.next(100)}, '{COUNTRIES[rnd.next(len(COUNTRIES))]}');")
    lines.append("")
    for i in range(1, BOOKS + 1):
        title = f"The {WORDS[rnd.next(len(WORDS))]} {WORDS[rnd.next(len(WORDS))]}"
        total = 1 + rnd.next(4)
        free = rnd.next(total + 1)
        lines.append(
            "INSERT INTO book (book_id, isbn, title, author_id, published_year, copies_total, copies_free) VALUES "
            f"({i}, '978-3-{10000 + i:05d}-{rnd.next(1000):03d}-{rnd.next(10)}', '{title} {i}', "
            f"{1 + rnd.next(AUTHORS)}, {1950 + rnd.next(76)}, {total}, {free});")
    lines.append("")
    for i in range(1, MEMBERS + 1):
        first, last = FIRST[rnd.next(len(FIRST))], LAST[rnd.next(len(LAST))]
        lines.append(
            "INSERT INTO member (member_id, email, full_name, joined_on, is_blocked) VALUES "
            f"({i}, '{first.lower()}.{last.lower()}.{i}@example.org', '{first} {last}', "
            f"DATE '2020-01-01' + {rnd.next(2000)}, {'TRUE' if rnd.next(25) == 0 else 'FALSE'});")
    lines.append("")
    for i in range(1, LOANS + 1):
        start = rnd.next(1800)
        returned = "NULL" if rnd.next(5) == 0 else f"DATE '2021-01-01' + {start + 1 + rnd.next(40)}"
        lines.append(
            "INSERT INTO loan (loan_id, book_id, member_id, loaned_on, due_on, returned_on) VALUES "
            f"({i}, {1 + rnd.next(BOOKS)}, {1 + rnd.next(MEMBERS)}, DATE '2021-01-01' + {start}, "
            f"DATE '2021-01-01' + {start + 21}, {returned});")
    lines += ["", "COMMIT;", ""]
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
